package com.example.silentmoon.frp.exercises.categorytheory.chapter1

fun <T> id(value: T): T {
  return value
}

fun <A> identity(): (A) -> A {
  return { it }
}

fun <A, B, C> compose(f: (B) -> C, g: (A) -> B): (A) -> C {
  return { a: A -> f(g(a)) }
}

/***
 * Явление, о котором идет речь, можно объяснить простым языком следующим образом:
 * Когда мы говорим о том, что одна функция может быть "составлена" из другой, это похоже на то, как мы можем комбинировать разные действия. Например, представьте, что у вас есть два действия: сначала вы добавляете 1 к числу, а затем умножаете результат на 2. Если вы сначала добавите 1, а потом умножите, это будет одно и то же, что если бы вы просто использовали специальную комбинацию, которая делает оба действия одновременно.
 * Теперь, если мы добавим еще одну функцию, которая просто возвращает число без изменений (это называется тождественной функцией), то, когда мы комбинируем её с любой другой функцией, результат останется прежним. Это похоже на то, как если бы вы смотрели в зеркало: ваше отражение — это вы, и ничего не меняется. Таким образом, мы можем сказать, что тождественная функция "не влияет" на результат, когда мы её комбинируем с другими функциями.
 * Это явление показывает, как функции могут взаимодействовать друг с другом, и как некоторые из них могут оставаться "невидимыми" в процессе, сохраняя исходные значения.
 */
fun sample1() {
  // Определяем тождественную функцию
  val id = identity<Int>()

  // Пример функции, которая увеличивает число на 1
  val addOne: (Int) -> Int = { x -> x + 1 }

  // Композиция с тождественной функцией
  val composedWithId = compose(id, addOne)

  // Проверка идентичности
  val testValue = 5
  val result = composedWithId(testValue)

  // Ожидаем, что результат будет равен addOne(testValue)
  val expected = addOne(testValue)

  // Выводим результаты
  println("Результат композиции: $result") // Ожидается 6
  println("Ожидаемое значение: $expected") // Ожидается 6
  println("Идентичность соблюдена: ${result == expected}") // Ожидается true
}